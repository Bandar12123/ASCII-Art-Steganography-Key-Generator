char get_symbol(unsigned char c)
{
    switch (c)
    {
    case 0: return ('.');
    case 1: return ('|');
    case 2: return ('/');
    case 3: return ('#');
    case 4: return ('!');
    case 5: return (',');
    case 6: return ('<');
    case 7: return ('>');
    default: return '\\';
    }
}

char get_background(unsigned char b)
{
    if (b) return (3);
    return (9);
}

void print_key(pixel board[32][32])
{
    unsigned char i, j;

    for (i = 0; i < 32; i++)
    {
        for (j = 0; j < 32; j++)
        {
            if (board[i][j].fields.visibility)
            {
                printf("\033[3%d;4%dm%c\033[0m",
                    board[i][j].fields.color,
                    get_background(board[i][j].fields.background),
                    get_symbol(board[i][j].fields.symbol));
            } else printf(" ");
        } printf("\n");
    }
}

int cmp_keys(pixel key1[32][32], pixel key2[32][32])
{
    unsigned char i, j;
    while (key1[i][j].raw == key2[i][j].raw)
    {
        j++;
        if (j == 32)
        {
            i++;
            j = 0;
            if (i == 32) return (1);
        }
    } return (0);
}

